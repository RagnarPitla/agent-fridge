// BodyHash identifies the canonical text currently shipped.
func BodyHash() string { return util.ShortHash(Body) }

// Block is the full generated block, markers included.
func Block() string {
	return "<!-- BEGIN WCP-ADAPTER v0.1 hash:" + BodyHash() + " -->\n" +
		"<!-- Generated by `" + brand.Bin + " adapters install`. Edit the protocol, not this block. -->\n" +
		Body + "\n" + End
}

// Splice inserts the block into an existing document without touching a byte
// of the rest.
func Splice(current, next string) (string, error) {
	if current == "" {
		return next + "\n", nil
	}
	begin := BeginRE.FindString(current)
	if begin == "" {
		sep := "\n\n"
		if strings.HasSuffix(current, "\n") {
			sep = "\n"
		}
		return current + sep + next + "\n", nil
	}
	start := strings.Index(current, begin)
	endIdx := strings.Index(current[start:], End)
	if endIdx == -1 {
		return "", errs.New("E_STATE_CORRUPT", "Found a start marker with no matching end marker.").
			WithHint("Delete the partial block by hand, then re-run: fridge adapters install")
	}
	endIdx += start
	return current[:start] + next + current[endIdx+len(End):], nil
}

// Status describes one vendor file.
type Status struct {
	Vendor    string
	File      string
	AbsPath   string
	Label     string
	State     string
	FoundHash string
	WantHash  string
	Action    string
}

// StatusFor inspects one vendor file.
func StatusFor(root, vendorKey string) Status {
	v := Vendors[vendorKey]
	file := filepath.Join(root, v.File)
	current, ok := fsx.ReadTextOr(file)
	found := ""
	if ok {
		if m := BeginRE.FindStringSubmatch(current); m != nil {
			found = m[1]
		}
	}
	state := "missing"
	switch {
	case !ok:
		state = "missing"
	case found == "":
		state = "absent"
	case found == BodyHash():
		state = "current"
	default:
		state = "drifted"
	}
	return Status{Vendor: vendorKey, File: v.File, AbsPath: file, Label: v.Label,
		State: state, FoundHash: found, WantHash: BodyHash()}
}

// Install writes or checks the block for each vendor.
func Install(root string, vendorKeys []string, check bool, tmpDir string) ([]Status, error) {
	results := []Status{}
	for _, key := range vendorKeys {
		if _, ok := Vendors[key]; !ok {
			return nil, errs.New("E_USAGE", "Unknown vendor '"+key+"'.").
				WithHint("Known: " + strings.Join(Order, ", "))
		}
		st := StatusFor(root, key)
		if !check && st.State != "current" {
			if err := fsx.EnsureDir(filepath.Dir(st.AbsPath)); err != nil {
				return nil, err
			}
			current, _ := fsx.ReadTextOr(st.AbsPath)
			next, err := Splice(current, Block())
			if err != nil {
				return nil, err
			}
			if err := fsx.WriteAtomic(st.AbsPath, next, tmpDir); err != nil {
				return nil, err
			}
			switch st.State {
			case "missing":
				st.Action = "created"
			case "absent":
				st.Action = "appended"
			default:
				st.Action = "updated"
			}
		} else if check {
			st.Action = "checked"
		} else {
			st.Action = "unchanged"
		}
		results = append(results, st)
	}
	return results, nil
}
