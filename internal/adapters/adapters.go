// BeginRE matches the generated block header and captures its body hash.
var BeginRE = regexp.MustCompile(`<!-- BEGIN WCP-ADAPTER v0\.1 hash:([0-9a-f]{12}) -->`)

// End closes a generated block.
const End = "<!-- END WCP-ADAPTER v0.1 -->"

// Vendor is one target instruction file.
type Vendor struct {
	Key   string
	File  string
	Label string
}

// Order is the stable vendor order used by every listing.
var Order = []string{"agents", "claude", "copilot", "codex", "cursor", "generic"}

// Vendors maps a vendor key to its target file.
var Vendors = map[string]Vendor{
	"agents":  {"agents", "AGENTS.md", "AGENTS.md (Codex, Copilot CLI, Amp, and anything that reads AGENTS.md)"},
	"claude":  {"claude", "CLAUDE.md", "Claude Code"},
	"copilot": {"copilot", filepath.Join(".github", "copilot-instructions.md"), "GitHub Copilot (IDE and CLI)"},
	"codex":   {"codex", filepath.Join(".codex", "instructions.md"), "OpenAI Codex (explicit file)"},
	"cursor":  {"cursor", filepath.Join(".cursor", "rules", "agent-fridge.mdc"), "Cursor"},
	"generic": {"generic", filepath.Join("docs", "AGENT-COORDINATION.md"), "Generic / any other tool"},
}

